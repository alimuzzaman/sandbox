def _write_abilities_muplugin(instance: str) -> None:
    """Drop the Sandbox Abilities mu-plugin (spec 003) into the instance.

    Registers `sandbox/*` abilities on the WP 6.9+ Abilities API so AI agents can
    run code / manage files in the live runtime. Copied from the maintained asset
    `sandbox/assets/abilities/00-sandbox-abilities.php` (a real, lintable PHP file)
    rather than an inline string. Host-file based, so it works on Docker AND herd.
    Idempotent; the mu-plugin self-gates on the Abilities API + an enable flag, so
    it no-ops on older WP. Mirrors _write_mail_muplugin."""
    asset_dir = Path(__file__).resolve().parent.parent / "assets" / "abilities"
    src = asset_dir / "00-sandbox-abilities.php"
    if not src.exists():
        return
    mu_dir = wp_dir(instance) / "wp-content" / "mu-plugins"
    mu_dir.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(src, mu_dir / "00-sandbox-abilities.php")
    # Copy the payload dir (vendored wordpress/mcp-adapter) that the loader
    # require_once's for the MCP-server exposure. Refresh in place each call.
    payload = asset_dir / "sandbox-abilities"
    if payload.is_dir():
        dest = mu_dir / "sandbox-abilities"
        if dest.exists():
            shutil.rmtree(dest)
        shutil.copytree(payload, dest)


_ONDEMAND_MU_TEMPLATE = r'''<?php
/**
 * Sandbox On-Demand Plugins (spec 010) — local dev only. Generated by ./sb.
 *
 * Slugs declared on-demand (or locally-sourced) in the sandbox config are listed
 * in sandbox-local-sources.json (slug -> {path|zip}). On any install attempt of
 * such a slug — Templately Full Site Import, wp-cli `plugin install`, or the
 * wp-admin "Add Plugin" flow — we serve the LOCAL copy instead of downloading:
 *   - plugins_api: make the slug "known" with a sentinel download_link.
 *   - upgrader_pre_download: swap the sentinel/slug for a THROWAWAY temp zip built
 *     from the local source (WP deletes the package it is handed — never the real
 *     source). Mirrors the dl-cache temp-copy rule.
 * Plus a Plugins-screen page listing on-demand plugins with one-click install.
 */
if ( ! defined( 'ABSPATH' ) ) { return; }

function sandbox_ondemand_map() {
	static $map = null;
	if ( null !== $map ) { return $map; }
	$map = array();
	$f = __DIR__ . '/sandbox-local-sources.json';
	if ( is_readable( $f ) ) {
		$d = json_decode( (string) file_get_contents( $f ), true );
		if ( is_array( $d ) ) { $map = $d; }
	}
	return $map;
}

/** Slug from a package URL/sentinel, or '' if not one of ours. */
function sandbox_ondemand_slug_for( $package ) {
	if ( ! is_string( $package ) || '' === $package ) { return ''; }
	if ( 0 === strpos( $package, 'sandbox-ondemand://' ) ) {
		return substr( $package, strlen( 'sandbox-ondemand://' ) );
	}
	// wp.org URL → slug (downloads.wordpress.org/plugin/<slug>.<ver>.zip)
	if ( preg_match( '#/plugin/([^/]+?)(\.\d[\d.]*)?\.zip#', $package, $m ) ) {
		$slug = $m[1];
		$map = sandbox_ondemand_map();
		if ( isset( $map[ $slug ] ) ) { return $slug; }
	}
	return '';
}

/** Build a throwaway temp zip for a slug's local source, or WP_Error. */
function sandbox_ondemand_local_zip( $slug ) {
	$map = sandbox_ondemand_map();
	if ( empty( $map[ $slug ] ) ) {
		return new WP_Error( 'sandbox_ondemand', "No local source for '$slug'." );
	}
	$entry = $map[ $slug ];
	if ( ! empty( $entry['zip'] ) ) {
		if ( ! is_readable( $entry['zip'] ) ) {
			return new WP_Error( 'sandbox_ondemand', "Local zip missing: {$entry['zip']}" );
		}
		$tmp = wp_tempnam( $slug . '.zip' );
		if ( ! @copy( $entry['zip'], $tmp ) ) {
			return new WP_Error( 'sandbox_ondemand', 'Could not copy local zip.' );
		}
		return $tmp;
	}
	$dir = isset( $entry['path'] ) ? $entry['path'] : '';
	if ( ! $dir || ! is_dir( $dir ) ) {
		return new WP_Error( 'sandbox_ondemand', "Local source dir missing: $dir" );
	}
	if ( ! class_exists( 'ZipArchive' ) ) {
		return new WP_Error( 'sandbox_ondemand', 'ZipArchive unavailable.' );
	}
	$tmp = wp_tempnam( $slug . '.zip' );
	$zip = new ZipArchive();
	if ( true !== $zip->open( $tmp, ZipArchive::CREATE | ZipArchive::OVERWRITE ) ) {
		return new WP_Error( 'sandbox_ondemand', 'Could not create temp zip.' );
	}
	$base = rtrim( $dir, '/' );
	$it = new RecursiveIteratorIterator(
		new RecursiveDirectoryIterator( $base, FilesystemIterator::SKIP_DOTS ),
		RecursiveIteratorIterator::SELF_FIRST );
	foreach ( $it as $file ) {
		$path = $file->getPathname();
		$rel  = $slug . '/' . ltrim( substr( $path, strlen( $base ) ), '/' );
		if ( $file->isDir() ) { $zip->addEmptyDir( $rel ); }
		else { $zip->addFile( $path, $rel ); }
	}
	$zip->close();
	return $tmp;
}

// Make on-demand slugs resolvable by the installer (wp-cli / wp-admin by slug).
add_filter( 'plugins_api', function ( $res, $action, $args ) {
	if ( 'plugin_information' !== $action || empty( $args->slug ) ) { return $res; }
	$map = sandbox_ondemand_map();
	if ( empty( $map[ $args->slug ] ) ) { return $res; }
	$slug = $args->slug;
	return (object) array(
		'name'          => $slug,
		'slug'          => $slug,
		'version'       => 'local',
		'download_link' => 'sandbox-ondemand://' . $slug,
		'sections'      => array( 'description' => 'Sandbox on-demand (local source).' ),
	);
}, 10, 3 );

// Serve the local copy for our sentinel / matched slug (throwaway temp zip).
add_filter( 'upgrader_pre_download', function ( $reply, $package, $upgrader ) {
	$slug = sandbox_ondemand_slug_for( $package );
	if ( '' === $slug ) { return $reply; }
	$zip = sandbox_ondemand_local_zip( $slug );
	return is_wp_error( $zip ) ? $zip : $zip;
}, 5, 3 );

// --- Admin: list on-demand plugins + one-click install-from-local -----------
add_action( 'admin_menu', function () {
	add_plugins_page(
		'Sandbox: On-Demand', 'Sandbox On-Demand',
		'manage_options', 'sandbox-ondemand', 'sandbox_ondemand_render' );
} );

function sandbox_ondemand_render() {
	if ( ! current_user_can( 'manage_options' ) ) { return; }
	if ( isset( $_POST['sandbox_ondemand_install'] ) ) {
		check_admin_referer( 'sandbox_ondemand' );
		$slug = isset( $_POST['slug'] ) ? sanitize_key( wp_unslash( $_POST['slug'] ) ) : '';
		require_once ABSPATH . 'wp-admin/includes/class-wp-upgrader.php';
		require_once ABSPATH . 'wp-admin/includes/plugin-install.php';
		$up  = new Plugin_Upgrader( new Automatic_Upgrader_Skin() );
		$res = $up->install( 'sandbox-ondemand://' . $slug );
		echo '<div class="notice notice-' . ( is_wp_error( $res ) || ! $res ? 'error' : 'success' ) .
			'"><p>' . esc_html( is_wp_error( $res ) ? $res->get_error_message() :
			( $res ? "Installed '$slug' from local." : "Install of '$slug' failed." ) ) . '</p></div>';
	}
	$map = sandbox_ondemand_map();
	echo '<div class="wrap"><h1>Sandbox: On-Demand Plugins</h1>';
	echo '<p>Declared with a local source; installed from your local copy on demand (no download).</p>';
	if ( empty( $map ) ) { echo '<p>None declared.</p></div>'; return; }
	echo '<table class="widefat striped"><thead><tr><th>Plugin</th><th>Source</th><th>State</th><th></th></tr></thead><tbody>';
	foreach ( $map as $slug => $entry ) {
		$src = isset( $entry['zip'] ) ? $entry['zip'] : ( isset( $entry['path'] ) ? $entry['path'] : '?' );
		$installed = file_exists( WP_PLUGIN_DIR . '/' . $slug );
		echo '<tr><td><strong>' . esc_html( $slug ) . '</strong></td><td><code>' . esc_html( $src ) . '</code></td><td>' .
			( $installed ? 'installed' : 'available' ) . '</td><td>';
		if ( ! $installed ) {
			echo '<form method="post" style="margin:0">';
			wp_nonce_field( 'sandbox_ondemand' );
			echo '<input type="hidden" name="slug" value="' . esc_attr( $slug ) . '">';
			echo '<button class="button button-primary" name="sandbox_ondemand_install" value="1">Install from local</button>';
			echo '</form>';
		}
		echo '</td></tr>';
	}
	echo '</tbody></table></div>';
}
'''


_DL_CACHE_MU_TEMPLATE = r'''<?php
/* Sandbox: cache plugin/theme zip downloads (Templately Full Site Import
   especially) so WP-runtime installs reuse a cached zip instead of
   re-downloading. Templately FSI installs deps via Plugin_Upgrader->install(
   $download_link ), which fires WP's upgrader_pre_download filter — we hook it.

   Cache key is the (version-specific) download URL. Freshness is enforced by an
   HTTP conditional revalidation (ETag / Last-Modified): we only ask upstream
   "is there a newer build?" once the throttle window (SANDBOX_DL_CACHE_TTL,
   default 12h) has elapsed; a 304 keeps the cached zip, a 200 replaces it.
   Within the window the cache is served with NO upstream call at all.

   WP_Upgrader deletes the package file we return (it treats it as a throwaway
   download temp), so we always hand back a temp COPY and keep the cache file.
   The cache dir is the shared host mount runtime/dl-cache/wp-http →
   /sandbox-dl-cache (web tier only; on wpcli the guard bails and `wp install`
   uses WP_CLI_CACHE_DIR, which is itself version-keyed). Generated by ./sb. */
if ( ! defined( 'SANDBOX_DL_CACHE_DIR' ) ) {
    define( 'SANDBOX_DL_CACHE_DIR', '/sandbox-dl-cache' );
}
add_filter( 'upgrader_pre_download', function ( $reply, $package, $upgrader ) {
    if ( false !== $reply ) { return $reply; }
    if ( ! is_string( $package ) || ! preg_match( '#^https?://#i', $package ) ) {
        return $reply;
    }
    $dir = SANDBOX_DL_CACHE_DIR;
    if ( ! is_dir( $dir ) || ! is_writable( $dir ) ) { return $reply; }
    if ( ! function_exists( 'wp_tempnam' ) ) {
        require_once ABSPATH . 'wp-admin/includes/file.php';
    }

    $key   = $dir . '/' . sha1( $package );
    $zip   = $key . '.zip';
    $metaf = $key . '.json';
    $tmpf  = $key . '.tmp.' . getmypid();
    $now   = time();
    $ttl   = defined( 'SANDBOX_DL_CACHE_TTL' ) ? (int) SANDBOX_DL_CACHE_TTL : 43200;

    // Hand WP a throwaway temp COPY so its post-unpack delete can't remove our
    // cached file. Returns false if the copy fails (caller then falls through).
    $serve = function () use ( $zip, $package ) {
        $t = wp_tempnam( $package );
        return ( $t && @copy( $zip, $t ) ) ? $t : false;
    };

    clearstatcache( true, $zip );
    $have = is_file( $zip ) && filesize( $zip ) > 0;
    $meta = $have ? ( @json_decode( (string) @file_get_contents( $metaf ), true ) ?: array() ) : array();

    // Inside the throttle window: trust the cache, no upstream call (cache HIT).
    if ( $have && ( $now - (int) ( isset( $meta['checked'] ) ? $meta['checked'] : 0 ) ) < $ttl ) {
        $s = $serve();
        if ( $s ) { return $s; }
    }

    // Throttle elapsed (or cache MISS): ask upstream. Conditional GET when we
    // already hold a copy — 304 = no newer version, 200 = a newer build.
    $cond = array();
    if ( $have ) {
        if ( ! empty( $meta['etag'] ) )          { $cond['If-None-Match']     = $meta['etag']; }
        if ( ! empty( $meta['last_modified'] ) ) { $cond['If-Modified-Since'] = $meta['last_modified']; }
    }
    $resp = wp_remote_get( $package, array(
        'headers'     => $cond,
        'timeout'     => 300,
        'redirection' => 5,
        'stream'      => true,
        'filename'    => $tmpf,   // stream to disk: no large zip held in memory
    ) );
    if ( is_wp_error( $resp ) ) {
        @unlink( $tmpf );
        if ( $have ) { $s = $serve(); if ( $s ) { return $s; } }  // offline: serve stale
        return $reply;
    }
    $code = (int) wp_remote_retrieve_response_code( $resp );
    if ( 304 === $code && $have ) {
        @unlink( $tmpf );
        $meta['checked'] = $now;                                  // reset the throttle clock
        @file_put_contents( $metaf, wp_json_encode( $meta ) );
        $s = $serve(); if ( $s ) { return $s; }
        return $reply;
    }
    clearstatcache( true, $tmpf );
    if ( 200 === $code && is_file( $tmpf ) && filesize( $tmpf ) > 0 ) {
        @rename( $tmpf, $zip );                                   // same dir ⇒ atomic swap
        @file_put_contents( $metaf, wp_json_encode( array(
            'url'           => $package,
            'etag'          => wp_remote_retrieve_header( $resp, 'etag' ),
            'last_modified' => wp_remote_retrieve_header( $resp, 'last-modified' ),
            'checked'       => $now,
            'size'          => filesize( $zip ),
        ) ) );
        $s = $serve(); if ( $s ) { return $s; }
    }
    @unlink( $tmpf );
    if ( $have ) { $s = $serve(); if ( $s ) { return $s; } }      // odd status: serve stale
    return $reply;                                                // give up → WP's own path
}, 5, 3 );
'''


