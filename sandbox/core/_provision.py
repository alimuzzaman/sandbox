    if platforms.is_dir():
        dest = mu_dir / "sandbox-licensing" / "platforms"
        if dest.parent.exists():
            shutil.rmtree(dest.parent)
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copytree(platforms, dest)
    _write_licensing_state(instance)


