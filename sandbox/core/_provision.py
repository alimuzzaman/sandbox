def _relax_perms_for_uid_switch(inst: str) -> None:
    """Make the instance's WP files readable+writable across web-server uids.

    apache/nginx serve as www-data (uid 33); OpenLiteSpeed runs lsphp as uid
    1000. The WP files are the SAME bind-mounted host dir (runtime/wp-<inst>) —
    switching servers doesn't move data, but files written under one uid must
    stay readable (and uploads writable) under the other. The real fix for a
    bind-mounted dev tree is permissive group/other bits: a+rX everywhere, and
    a+rwX on the writable trees (uploads, cache, upgrade). No sudo, no chown —
    works whoever owns the files on the host."""
    root = wp_dir(inst)
    if not root.exists():
        return
    info(f"relaxing file perms on {root.name} so both web-server uids can read/write…")
    for p in root.rglob("*"):
        try:
            if p.is_dir():
                p.chmod(p.stat().st_mode | 0o055)        # a+rx on dirs
            else:
                p.chmod(p.stat().st_mode | 0o044)        # a+r on files
        except OSError:
            pass
    # The trees WP writes to at runtime need group/other write too.
    for sub in ("wp-content/uploads", "wp-content/cache", "wp-content/upgrade"):
        d = root / sub
        for p in [d, *d.rglob("*")] if d.exists() else []:
            try:
                p.chmod(p.stat().st_mode | (0o022 if p.is_dir() else 0o022))
            except OSError:
                pass


def _wire_project_plugins(name: str, root: str, pconf: dict) -> None:
    """Wire the project's plugins into the instance from the canonical resolved
    map (spec 010: `plugins_resolved` = {slug: {source, active, on_demand}}).

    Per entry: local path -> symlink under the SLUG KEY (worktree-safe); zip/org ->
    install; activate per state; on-demand -> NOT installed (its local source is
    registered into the local-source map the mu-plugin serves on install). Legacy
    non-plugin `mappings`/`mappings_inactive` (other wp-paths) are still handled
    here. NOTE: absolute symlinks only resolve inside the container when the target
    is under a bind-mounted host path (the extra_mounts collector handles that)."""
    pdir = plugins_dir(name)
    pdir.mkdir(parents=True, exist_ok=True)
    root_path = Path(root)
    wp_root = wp_dir(name)

    def _abs(val: str) -> Path:
        p = Path(str(val)).expanduser()
        return p if p.is_absolute() else (root_path / p).resolve()

    resolved = pconf.get("plugins_resolved")
    if not isinstance(resolved, dict):
        resolved = {}

    activate: list[str] = []            # slugs to activate (symlinked or present)
    org_install_active, org_install_inactive = [], []
    zip_install_active, zip_install_inactive = [], []
    local_sources: dict[str, dict] = {}  # slug -> {path|zip} for the mu-plugin

    for slug, e in resolved.items():
        src = e.get("source") or {"kind": "org", "value": None}
        kind = src.get("kind")
        if e.get("on_demand"):
            # Do NOT install now; register a LOCAL source so any later install
            # attempt (FSI / wp-cli / wp-admin) is served from local.
            if kind == "path":
                p = _abs(src["value"])
                if p.exists():
                    local_sources[slug] = {"path": str(p)}
            elif kind == "zip":
                local_sources[slug] = {"zip": src["value"]}
            continue  # org on-demand: nothing to register (WP pulls org on demand)
        if kind == "path":
            p = _abs(src["value"])
            if not p.exists():
                info(f"plugin '{slug}': local source not found at {p} — skipping "
                     f"(not falling back to org).")
                continue
            _force_symlink(pdir / slug, p)         # slug = map KEY (worktree-safe)
            local_sources[slug] = {"path": str(p)}  # also serve local on re-install
            if e.get("active"):
                activate.append(slug)
        elif kind == "zip":
            (zip_install_active if e.get("active") else zip_install_inactive).append(
                src["value"])
        else:  # org
            if (pdir / slug).exists():
                if e.get("active"):
                    activate.append(slug)
            else:
                (org_install_active if e.get("active") else org_install_inactive).append(
                    slug)

    # Legacy NON-plugin mappings (wp-paths that aren't wp-content/plugins/<slug>):
    # symlink as before. Plugin-path mappings were folded into plugins_resolved.
    for key in ("mappings", "mappings_inactive"):
        for wp_path, src in (pconf.get(key) or {}).items():
            parts = str(wp_path).strip("/").split("/")
            is_plugin = (len(parts) == 3 and parts[0] == "wp-content"
                         and parts[1] == "plugins")
            if is_plugin:
                continue  # handled via plugins_resolved
            src_p = _abs(src)
            if src_p.exists():
                dest = wp_root / str(wp_path)
                dest.parent.mkdir(parents=True, exist_ok=True)
                _force_symlink(dest, src_p)

    if org_install_active:
        wpcli(["plugin", "install", *org_install_active, "--activate"],
              instance=name, check=False)
    if org_install_inactive:
        wpcli(["plugin", "install", *org_install_inactive], instance=name, check=False)
    if zip_install_active:
        wpcli(["plugin", "install", *zip_install_active, "--activate"],
              instance=name, check=False)
    if zip_install_inactive:
        wpcli(["plugin", "install", *zip_install_inactive], instance=name, check=False)
    if activate:
        wpcli(["plugin", "activate", *activate], instance=name, check=False)

    _write_local_sources(name, local_sources)


def _pkg_slug(entry: str) -> str:
    """Best-effort slug from a plugin/theme entry: wp.org slug as-is; zip URL by
    basename minus the version tail (twentytwentyfour.1.5.zip →
    twentytwentyfour); local path by directory name."""
    if entry.startswith("http"):
        base = entry.rstrip("/").rsplit("/", 1)[-1]
        base = base[:-4] if base.endswith(".zip") else base
        return re.sub(r"\.\d[\d.]*$", "", base)
    if "/" in entry or entry.startswith((".", "~")):
        return Path(entry).expanduser().name
    return entry


def _wire_project_themes(name: str, root: str, pconf: dict) -> None:
    """Install the project's `themes` and activate the FIRST one. Same entry
    forms as plugins: wp.org slug, zip URL, or local path (symlinked in —
    needs an extra_mounts bind like plugin paths do). Activation is a
    separate explicit step: `theme install --activate` is silently ignored
    on multisite installs."""
    themes = [t for t in (pconf.get("themes") or []) if t and isinstance(t, str)]
    if not themes:
        return
    tdir = wp_dir(name) / "wp-content" / "themes"
    tdir.mkdir(parents=True, exist_ok=True)
    root_path = Path(root)
    for entry in themes:
        if entry.startswith("http") and entry.endswith(".zip"):
            if (tdir / _pkg_slug(entry)).exists():
                continue  # already present (bundled / prior provision) — skip noisy reinstall
            wpcli(["theme", "install", entry], instance=name, check=False)
        elif "/" in entry or entry.startswith((".", "~")):
            src = Path(entry).expanduser()
            if not src.is_absolute():
                src = (root_path / entry).resolve()
            if src.exists():
                _force_symlink(tdir / src.name, src)
        elif (tdir / _pkg_slug(entry)).exists():
            # Already present (e.g. a default theme bundled with WP core, or a
            # prior provision). Reinstalling only emits "Destination folder
            # already exists" + "Error: No themes installed." noise — skip it.
            continue
        else:
            wpcli(["theme", "install", entry], instance=name, check=False)
    wpcli(["theme", "activate", _pkg_slug(themes[0])],
          instance=name, check=False)
